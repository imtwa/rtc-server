#!/usr/bin/env bash
# ============================================================================
# WebRTC 信令 + TURN 服务 · 环境变量配置脚本
#
# 用法：
#   ./init-env.sh                        交互式配置（推荐）
#   ./init-env.sh --ip 1.2.3.4 --domain rtc.example.com
#   ./init-env.sh --ip 1.2.3.4 --domain rtc.example.com --force
#
# 行为：
#   · 自动生成 TURN_SECRET（openssl rand -hex 32）
#   · 已存在 .env 时默认**不覆盖**，除非显式传 --force
#   · 生成后自动校验必填项
#
# 注意：.env 含密钥，已在 .gitignore 中排除，切勿提交。
# ============================================================================
set -euo pipefail

cd "$(dirname "$0")"

ENV_FILE=".env"

IP=""
DOMAIN=""
FORCE=0

# ---------------------------------------------------------------------------
# 参数解析
# ---------------------------------------------------------------------------

while [ $# -gt 0 ]; do
    case "$1" in
        --ip)     IP="${2:-}"; shift 2 ;;
        --domain) DOMAIN="${2:-}"; shift 2 ;;
        --force)  FORCE=1; shift ;;
        -h|--help)
            sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'
            exit 0
            ;;
        *)
            echo "[错误] 未知参数：$1" >&2
            echo "       用法：$0 [--ip <公网IP>] [--domain <域名>] [--force]" >&2
            exit 1
            ;;
    esac
done

# ---------------------------------------------------------------------------
# 已有配置保护
# ---------------------------------------------------------------------------

if [ -f "$ENV_FILE" ] && [ "$FORCE" -ne 1 ]; then
    echo "[提示] $ENV_FILE 已存在，未做任何修改。"
    echo ""
    echo "  查看当前配置：  grep -v '^#' $ENV_FILE | grep -v '^$'"
    echo "  覆盖重配：      $0 --ip <公网IP> --domain <域名> --force"
    echo ""
    echo "  若只想改某一项，直接编辑 $ENV_FILE 即可。"
    exit 0
fi

# ---------------------------------------------------------------------------
# 采集输入
# ---------------------------------------------------------------------------

# 已有 .env 时从里面取默认值，避免重配时又要手输一遍
if [ -f "$ENV_FILE" ]; then
    [ -z "$IP" ]     && IP=$(grep -E '^TURN_PUBLIC_IP=' "$ENV_FILE" | head -1 | cut -d= -f2- | tr -d '"' | xargs || true)
    [ -z "$DOMAIN" ] && DOMAIN=$(grep -E '^TURN_DOMAIN=' "$ENV_FILE" | head -1 | cut -d= -f2- | tr -d '"' | xargs || true)
fi

if [ -z "$IP" ]; then
    printf '服务器公网 IP（不是域名、不是内网 IP）：'
    read -r IP
fi

if [ -z "$DOMAIN" ]; then
    printf 'TURN 域名（需 DNS 解析到上面的 IP，如 rtc.example.com）：'
    read -r DOMAIN
fi

# 基本校验，避免填反
if [ -z "$IP" ] || [ -z "$DOMAIN" ]; then
    echo "[错误] IP 与域名都不能为空" >&2
    exit 1
fi

if ! echo "$IP" | grep -qE '^[0-9]{1,3}(\.[0-9]{1,3}){3}$'; then
    echo "[警告] '$IP' 看起来不是 IPv4 地址。"
    echo "       TURN_PUBLIC_IP 必须是公网 IP，不能填域名。"
    printf '       仍要继续？(y/N) '
    read -r ans
    case "$ans" in
        y|Y) ;;
        *) echo "已取消"; exit 1 ;;
    esac
fi

if echo "$DOMAIN" | grep -qE '^[0-9]{1,3}(\.[0-9]{1,3}){3}$'; then
    echo "[警告] '$DOMAIN' 看起来是 IP。TURN_DOMAIN 应是域名。"
    printf '       仍要继续？(y/N) '
    read -r ans
    case "$ans" in
        y|Y) ;;
        *) echo "已取消"; exit 1 ;;
    esac
fi

# ---------------------------------------------------------------------------
# 生成密钥
# ---------------------------------------------------------------------------

if command -v openssl >/dev/null 2>&1; then
    SECRET=$(openssl rand -hex 32)
else
    # 无 openssl 时退回 /dev/urandom，仍取 32 字节的十六进制表示
    SECRET=$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')
    echo "[提示] 未找到 openssl，已用 /dev/urandom 生成密钥"
fi

if [ -z "$SECRET" ]; then
    echo "[错误] 密钥生成失败" >&2
    exit 1
fi

# ---------------------------------------------------------------------------
# 写入
# ---------------------------------------------------------------------------

# 覆盖前先备份，避免手滑丢掉已有配置
if [ -f "$ENV_FILE" ]; then
    cp "$ENV_FILE" "${ENV_FILE}.bak"
    echo "[提示] 原 $ENV_FILE 已备份为 ${ENV_FILE}.bak"
fi

cat > "$ENV_FILE" <<EOF
# ============================================================================
# WebRTC 信令 + TURN 服务 · 环境变量
#
# 由 init-env.sh 生成于 $(date '+%Y-%m-%d %H:%M:%S')
#
# 本文件含密钥，已在 .gitignore 中排除，切勿提交到仓库。
# 修改后需重启服务：./deploy.sh up
# ============================================================================

# ---------------------------------------------------------------------------
# 服务器公网 IP（必填）
#
# 必须是公网 IP，不能填域名、不能填内网 IP。
# 云主机是 1:1 NAT，内网 IP 与公网 IP 不同 —— 填错会让 coturn 把内网地址
# 写进 relay 候选，客户端拿到不可达地址，ICE 一直 checking 直到 failed，
# 且日志里没有任何报错。
# ---------------------------------------------------------------------------
TURN_PUBLIC_IP=$IP

# ---------------------------------------------------------------------------
# TURN 域名（必填）
#
# 下发给客户端使用，需在 DNS 添加 A 记录指向上面的 IP。
# 用域名而非 IP 的好处：换机器时只改 DNS，客户端不必重新配置。
# ---------------------------------------------------------------------------
TURN_DOMAIN=$DOMAIN

# ---------------------------------------------------------------------------
# TURN 长期密钥（必填，已自动生成）
#
# 信令服务用它签发临时凭据，coturn 用同一值校验 HMAC。
# 两端由同一份 .env 注入，因此天然一致。
#
# 轮换方式：重新运行 ./init-env.sh --force，然后 ./deploy.sh up
# ---------------------------------------------------------------------------
TURN_SECRET=$SECRET

# ---------------------------------------------------------------------------
# 端口
#
# 均避开惯例值（3478/5349），减少公网扫描器的探测噪音。
# 改端口不需要修改客户端 —— ICE 配置由服务端运行时签发。
# 改后须同步安全组放行范围。
# ---------------------------------------------------------------------------

# TURN / STUN 监听端口（TCP + UDP）
TURN_PORT=34780

# TURN over TLS 端口（需给 coturn 配证书后才启用）
TURN_TLS_PORT=53490

# TURN 中继端口段（UDP）
#
# 容量换算：一个 allocation 占 1 个端口；一条走中继的连接需两端各一个，
# 即 2 个。mesh 房间 N 人总占用 N×(N-1)。
# 默认区间（16384 个）理论上支持上百人，但实际瓶颈通常是带宽而非端口数：
# TURN 双向转发，3 人全中继约需 7 Mbps，轻量服务器通常只有 3-5 Mbps。
TURN_RELAY_MIN=49152
TURN_RELAY_MAX=65535

# ---------------------------------------------------------------------------
# 跨域放行来源
#
# 原生 App 不受同源限制，保持 * 即可。
# 浏览器端上线后建议收窄，例如：ALLOW_ORIGIN=https://app.example.com
# ---------------------------------------------------------------------------
ALLOW_ORIGIN=*
EOF

chmod 600 "$ENV_FILE"

# ---------------------------------------------------------------------------
# 结果
# ---------------------------------------------------------------------------

echo ""
echo "[完成] 已生成 $ENV_FILE（权限 600）"
echo ""
echo "  公网 IP：  $IP"
echo "  域名：     $DOMAIN"
echo "  密钥：     ${SECRET:0:8}...（共 64 字符，已隐藏）"
echo ""
echo "下一步："
echo "  1. 确认 DNS：$DOMAIN 的 A 记录已指向 $IP"
echo "  2. 放行安全组：34780 (TCP+UDP)、49152-65535 (UDP)"
echo "  3. 启动服务：  ./deploy.sh up"
echo "  4. 验证服务：  ./deploy.sh verify"
